/**
 * Writes the Arch package (PKGBUILD and .SRCINFO) for a release into a folder. It repackages the release's Linux
 * tarball, Electron included, into /opt. The release workflow builds `<id>` from it for its own pacman repo, and
 * pushes `<id>-bin` to the AUR: `node scripts/arch-package.ts <pkgname> <version> <tarball sha256> <out dir>`.
 *
 * .SRCINFO is written here rather than by `makepkg --printsrcinfo`, so the AUR job needs no Arch container. Both come
 * from the same fields; check them against makepkg after changing this file (docs/features/releases.md).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import pkg from "../package.json" with { type: "json" };
import { BRAND } from "../packages/contracts/src/brand.ts";

/** The package's name, and what it needs to know about one release. */
export interface ArchRelease {
  pkgname: string;
  version: string;
  sha256: string;
}

/** The pacman repo's package takes the app's own name; the AUR's takes `-bin`, as AUR packages of builds do. */
export const PKGNAMES = [BRAND.id, `${BRAND.id}-bin`];

/** The runtime libraries the bundled Electron links against: the same set electron-builder's .deb depends on. */
const DEPENDS = [
  "gtk3",
  "libnotify",
  "nss",
  "libxss",
  "libxtst",
  "xdg-utils",
  "at-spi2-core",
  "util-linux-libs",
  "libsecret",
];

const tarball = (version: string) => `${BRAND.id}-${version}-linux-x64`;
const sourceUrl = (version: string) => `${pkg.homepage}/releases/download/v${version}/${tarball(version)}.tar.gz`;
const quote = (value: string) => `"${value.replace(/["$`\\]/g, "\\$&")}"`;
const list = (values: readonly string[]) => `(${values.map((value) => `'${value}'`).join(" ")})`;
/** A package named otherwise stands in for, and can't sit beside, one with the app's own name. */
const replaces = (pkgname: string) => (pkgname === BRAND.id ? [] : [BRAND.id]);
/** `Name <me@example.com>` → `Name <me at example dot com>`, the AUR's usual form. */
const maintainer = pkg.author.replace(
  /<(.+)@(.+)>/,
  (_, user: string, host: string) => `<${user} at ${host.replaceAll(".", " dot ")}>`,
);

export function pkgbuild({ pkgname, version, sha256 }: ArchRelease): string {
  const dir = tarball("${pkgver}");
  const desktopEntry = [
    "[Desktop Entry]",
    `Name=${BRAND.name}`,
    `Comment=${pkg.description}`,
    `Exec=/usr/bin/${BRAND.id} %U`,
    `Icon=${BRAND.id}`,
    "Type=Application",
    "Terminal=false",
    "Categories=Development;",
    `StartupWMClass=${BRAND.id}`,
  ];
  const others = replaces(pkgname);
  const alternatives = others.length > 0 ? `provides=${list(others)}\nconflicts=${list(others)}\n` : "";
  return `# Generated by scripts/arch-package.ts in ${pkg.homepage}: change it there, not here.
# Maintainer: ${maintainer}
pkgname=${pkgname}
pkgver=${version}
pkgrel=1
pkgdesc=${quote(pkg.description)}
arch=('x86_64')
url=${quote(pkg.homepage)}
license=('${pkg.license}')
depends=${list(DEPENDS)}
${alternatives}options=('!strip' '!debug')
source=("${dir}.tar.gz::${sourceUrl("${pkgver}")}")
sha256sums=('${sha256}')

package() {
  install -d "$pkgdir/opt/${BRAND.id}" "$pkgdir/usr/bin"
  cp -a "${dir}/." "$pkgdir/opt/${BRAND.id}/"
  ln -s "/opt/${BRAND.id}/${BRAND.id}" "$pkgdir/usr/bin/${BRAND.id}"
  install -Dm644 "${dir}/resources/web/favicons/a-card.svg" "$pkgdir/usr/share/icons/hicolor/scalable/apps/${BRAND.id}.svg"
  install -Dm644 "${dir}/LICENSE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 /dev/stdin "$pkgdir/usr/share/applications/${BRAND.id}.desktop" <<EOF
${desktopEntry.join("\n")}
EOF
}
`;
}

export function srcinfo({ pkgname, version, sha256 }: ArchRelease): string {
  const fields: [string, string][] = [
    ["pkgdesc", pkg.description],
    ["pkgver", version],
    ["pkgrel", "1"],
    ["url", pkg.homepage],
    ["arch", "x86_64"],
    ["license", pkg.license],
    ...DEPENDS.map((name): [string, string] => ["depends", name]),
    ...replaces(pkgname).map((name): [string, string] => ["provides", name]),
    ...replaces(pkgname).map((name): [string, string] => ["conflicts", name]),
    ["options", "!strip"],
    ["options", "!debug"],
    ["source", `${tarball(version)}.tar.gz::${sourceUrl(version)}`],
    ["sha256sums", sha256],
  ];
  return `pkgbase = ${pkgname}\n${fields.map(([key, value]) => `\t${key} = ${value}\n`).join("")}\npkgname = ${pkgname}\n`;
}

if (import.meta.main) {
  const [pkgname = "", version, sha256, out] = process.argv.slice(2);
  const valid = PKGNAMES.includes(pkgname) && /^[\d.]+$/.test(version ?? "") && /^[\da-f]{64}$/.test(sha256 ?? "");
  if (!valid || !version || !sha256 || !out) {
    console.error(`Usage: node scripts/arch-package.ts <${PKGNAMES.join("|")}> <version> <tarball sha256> <out dir>`);
    process.exit(1);
  }
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "PKGBUILD"), pkgbuild({ pkgname, version, sha256 }));
  writeFileSync(join(out, ".SRCINFO"), srcinfo({ pkgname, version, sha256 }));
  console.log(`wrote ${pkgname} ${version} to ${out}`);
}
