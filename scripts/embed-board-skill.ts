/**
 * Writes `packages/contracts/src/boardSkill.ts` from `skills/aboard/SKILL.md` and `AGENTS-snippet.md`, so the server
 * can install the skill without the repo's files. Run with `pnpm skill:embed` after editing either file;
 * `apps/server/src/skills.test.ts` fails while they differ. The product name becomes `BRAND`, so a rename carries over.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const pkg = JSON.parse(readFileSync(`${root}package.json`, "utf8")) as { name: string; displayName: string };
const read = (path: string) => readFileSync(`${root}${path}`, "utf8").replace(/\r\n/g, "\n");

const BACKSLASH = "\\";
const escapeForBrand = (text: string, word: string, expr: string) => text.split(word).join(`\${${expr}}`);
/** The text as the inside of a template literal, with the product's id and name read from BRAND. */
const literal = (text: string) =>
  escapeForBrand(
    escapeForBrand(
      text
        .split(BACKSLASH)
        .join(BACKSLASH + BACKSLASH)
        .split("`")
        .join(`${BACKSLASH}\``)
        .split("${")
        .join(`${BACKSLASH}\${`),
      pkg.displayName,
      "BRAND.name",
    ),
    pkg.name,
    "BRAND.id",
  );

const skill = read("skills/aboard/SKILL.md");
const parts = /^---\nname: (.*)\ndescription: (.*)\n---\n\n([\s\S]*)$/.exec(skill);
if (!parts || parts[1] !== pkg.name) {
  throw new Error(`skills/aboard/SKILL.md must start with frontmatter naming it ${pkg.name}, then a description`);
}
const [, , description, body] = parts;

writeFileSync(
  `${root}packages/contracts/src/boardSkill.ts`,
  `// Generated by \`pnpm skill:embed\` from skills/aboard/. Edit those files, not this one.
import { BRAND } from "./brand.ts";

/**
 * The board skill agents install to learn the workflow. \`skills/aboard/SKILL.md\` ships the same text (a test keeps
 * them identical); it lives here so the bundled server can install and keep it in sync without the repo's files.
 */
export const BOARD_SKILL_DESCRIPTION = \`${literal(description!)}\`;

export const BOARD_SKILL_BODY = \`${literal(body!)}\`;

/** The snippet users paste into their own AGENTS.md; \`skills/aboard/AGENTS-snippet.md\` ships the same text. */
export const BOARD_AGENTS_SNIPPET = \`${literal(read("skills/aboard/AGENTS-snippet.md"))}\`;

/** The installed \`SKILL.md\`: frontmatter named after the folder it goes in, then the body. */
export function boardSkillFile(): string {
  return \`---\\nname: \${BRAND.id}\\ndescription: \${BOARD_SKILL_DESCRIPTION}\\n---\\n\\n\${BOARD_SKILL_BODY}\`;
}
`,
);
console.log("Wrote packages/contracts/src/boardSkill.ts");
