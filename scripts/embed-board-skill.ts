/**
 * Writes `packages/contracts/src/boardSkill.ts` from the skills the board ships: `skills/aboard/` (SKILL.md and
 * `AGENTS-snippet.md`) and `skills/aboard-automations/` (SKILL.md), so the server can install them without the repo's
 * files. Run with `pnpm skill:embed` after editing any of them; `apps/server/src/skills.test.ts` fails while they differ.
 * The product name becomes `BRAND`, so a rename carries over.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const pkg = JSON.parse(readFileSync(`${root}package.json`, "utf8")) as { name: string; displayName: string };
const read = (path: string) => readFileSync(`${root}${path}`, "utf8").replace(/\r\n/g, "\n");

const BACKSLASH = "\\";
const escapeForBrand = (text: string, word: string, expr: string) => text.split(word).join(`\${${expr}}`);
/** The text as the inside of a template literal, with the product's id, name and env prefix read from BRAND. */
const literal = (text: string) =>
  escapeForBrand(
    escapeForBrand(
      escapeForBrand(
        text
          .split(BACKSLASH)
          .join(BACKSLASH + BACKSLASH)
          .split("`")
          .join(`${BACKSLASH}\``)
          .split("${")
          .join(`${BACKSLASH}\${`),
        pkg.displayName,
        "BRAND.name",
      ),
      pkg.name,
      "BRAND.id",
    ),
    `${pkg.name.toUpperCase().replace(/[^A-Z0-9]/g, "_")}_`,
    'brandEnv("")',
  );

/** A shipped skill: its folder under `skills/`, the installed folder's name after BRAND.id, and its constants' prefix. */
const SKILLS = [
  { key: "board", dir: "aboard", suffix: "", constant: "BOARD", fn: "boardSkillFile" },
  {
    key: "automations",
    dir: "aboard-automations",
    suffix: "-automations",
    constant: "AUTOMATIONS",
    fn: "automationsSkillFile",
  },
] as const;

const parsed = SKILLS.map((skill) => {
  const path = `skills/${skill.dir}/SKILL.md`;
  const name = `${pkg.name}${skill.suffix}`;
  const parts = /^---\nname: (.*)\ndescription: (.*)\n---\n\n([\s\S]*)$/.exec(read(path));
  if (!parts || parts[1] !== name) {
    throw new Error(`${path} must start with frontmatter naming it ${name}, then a description`);
  }
  return { ...skill, description: parts[2]!, body: parts[3]! };
});

const sections = parsed.map(
  (
    skill,
  ) => `/** The ${skill.key} skill's frontmatter description; \`skills/${skill.dir}/SKILL.md\` ships the same text. */
export const ${skill.constant}_SKILL_DESCRIPTION = \`${literal(skill.description)}\`;

export const ${skill.constant}_SKILL_BODY = \`${literal(skill.body)}\`;

/** The installed \`SKILL.md\`: frontmatter named after the folder it goes in, then the body. */
export function ${skill.fn}(): string {
  return \`---\nname: \${BRAND.id}${skill.suffix}\ndescription: \${${skill.constant}_SKILL_DESCRIPTION}\n---\n\n\${${skill.constant}_SKILL_BODY}\`;
}`,
);

writeFileSync(
  `${root}packages/contracts/src/boardSkill.ts`,
  `// Generated by \`pnpm skill:embed\` from skills/aboard/ and skills/aboard-automations/. Edit those files, not this one.
import { BRAND, brandEnv } from "./brand.ts";

// The skills agents install to learn the board. The \`skills/<name>/SKILL.md\` files ship the same text (a test keeps
// them identical); it lives here so the bundled server can install and keep them in sync without the repo's files.

${sections.join("\n\n")}

/** The snippet users paste into their own AGENTS.md; \`skills/aboard/AGENTS-snippet.md\` ships the same text. */
export const BOARD_AGENTS_SNIPPET = \`${literal(read("skills/aboard/AGENTS-snippet.md"))}\`;

/** A skill the board installs into harnesses: the folder it goes in (under their \`skills/\`) and its \`SKILL.md\`. */
export interface ShippedSkill {
  key: ${parsed.map((s) => `"${s.key}"`).join(" | ")};
  /** The installed folder's name, which the frontmatter's \`name\` repeats. */
  id: string;
  file: () => string;
}

/** Every skill the board installs and keeps in sync, in the order the settings page names them. */
export const SHIPPED_SKILLS: readonly ShippedSkill[] = [
${parsed
  .map((s) => `  { key: "${s.key}", id: ${s.suffix ? `\`\${BRAND.id}${s.suffix}\`` : "BRAND.id"}, file: ${s.fn} },`)
  .join("\n")}
];
`,
);
console.log("Wrote packages/contracts/src/boardSkill.ts");
