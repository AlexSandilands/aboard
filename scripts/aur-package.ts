/**
 * Writes the AUR package (`<id>-bin`: PKGBUILD and .SRCINFO) for a release into a folder, ready to commit to the AUR's
 * git repo. It repackages the release's Linux tarball, Electron included, into /opt. The release workflow runs it once
 * the tarball is on the release: `node scripts/aur-package.ts <version> <tarball sha256> <out dir>`.
 *
 * .SRCINFO is written here rather than by `makepkg --printsrcinfo`, so the workflow needs no Arch container. Both come
 * from the same fields; check them against makepkg after changing this file (docs/features/releases.md).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import pkg from "../package.json" with { type: "json" };
import { BRAND } from "../packages/contracts/src/brand.ts";

/** What the AUR package needs to know about one release. */
export interface AurRelease {
  version: string;
  sha256: string;
}

/** The runtime libraries the bundled Electron links against: the same set electron-builder's .deb depends on. */
const DEPENDS = [
  "gtk3",
  "libnotify",
  "nss",
  "libxss",
  "libxtst",
  "xdg-utils",
  "at-spi2-core",
  "util-linux-libs",
  "libsecret",
];

const pkgname = `${BRAND.id}-bin`;
const tarball = (version: string) => `${BRAND.id}-${version}-linux-x64`;
const sourceUrl = (version: string) => `${pkg.homepage}/releases/download/v${version}/${tarball(version)}.tar.gz`;
const quote = (value: string) => `"${value.replace(/["$`\\]/g, "\\$&")}"`;
const list = (values: readonly string[]) => `(${values.map((value) => `'${value}'`).join(" ")})`;
/** `Name <me@example.com>` → `Name <me at example dot com>`, the AUR's usual form. */
const maintainer = pkg.author.replace(
  /<(.+)@(.+)>/,
  (_, user: string, host: string) => `<${user} at ${host.replaceAll(".", " dot ")}>`,
);

export function pkgbuild({ version, sha256 }: AurRelease): string {
  const dir = tarball("${pkgver}");
  const desktopEntry = [
    "[Desktop Entry]",
    `Name=${BRAND.name}`,
    `Comment=${pkg.description}`,
    `Exec=/usr/bin/${BRAND.id} %U`,
    `Icon=${BRAND.id}`,
    "Type=Application",
    "Terminal=false",
    "Categories=Development;",
    `StartupWMClass=${BRAND.id}`,
  ];
  return `# Generated by scripts/aur-package.ts in ${pkg.homepage}: change it there, not here.
# Maintainer: ${maintainer}
pkgname=${pkgname}
pkgver=${version}
pkgrel=1
pkgdesc=${quote(pkg.description)}
arch=('x86_64')
url=${quote(pkg.homepage)}
license=('${pkg.license}')
depends=${list(DEPENDS)}
provides=('${BRAND.id}')
conflicts=('${BRAND.id}')
options=('!strip' '!debug')
source=("${dir}.tar.gz::${sourceUrl("${pkgver}")}")
sha256sums=('${sha256}')

package() {
  install -d "$pkgdir/opt/${BRAND.id}" "$pkgdir/usr/bin"
  cp -a "${dir}/." "$pkgdir/opt/${BRAND.id}/"
  ln -s "/opt/${BRAND.id}/${BRAND.id}" "$pkgdir/usr/bin/${BRAND.id}"
  install -Dm644 "${dir}/resources/web/favicons/a-card.svg" "$pkgdir/usr/share/icons/hicolor/scalable/apps/${BRAND.id}.svg"
  install -Dm644 "${dir}/LICENSE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 /dev/stdin "$pkgdir/usr/share/applications/${BRAND.id}.desktop" <<EOF
${desktopEntry.join("\n")}
EOF
}
`;
}

export function srcinfo({ version, sha256 }: AurRelease): string {
  const fields: [string, string][] = [
    ["pkgdesc", pkg.description],
    ["pkgver", version],
    ["pkgrel", "1"],
    ["url", pkg.homepage],
    ["arch", "x86_64"],
    ["license", pkg.license],
    ...DEPENDS.map((name): [string, string] => ["depends", name]),
    ["provides", BRAND.id],
    ["conflicts", BRAND.id],
    ["options", "!strip"],
    ["options", "!debug"],
    ["source", `${tarball(version)}.tar.gz::${sourceUrl(version)}`],
    ["sha256sums", sha256],
  ];
  return `pkgbase = ${pkgname}\n${fields.map(([key, value]) => `\t${key} = ${value}\n`).join("")}\npkgname = ${pkgname}\n`;
}

if (import.meta.main) {
  const [version, sha256, out] = process.argv.slice(2);
  if (!version || !/^[\d.]+$/.test(version) || !sha256 || !/^[\da-f]{64}$/.test(sha256) || !out) {
    console.error("Usage: node scripts/aur-package.ts <version> <tarball sha256> <out dir>");
    process.exit(1);
  }
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "PKGBUILD"), pkgbuild({ version, sha256 }));
  writeFileSync(join(out, ".SRCINFO"), srcinfo({ version, sha256 }));
  console.log(`wrote ${pkgname} ${version} to ${out}`);
}
